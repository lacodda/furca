#[test]
fn a_red_ci_stops_before_the_tag_and_resume_carries_on() {
    let pair = Pair::new(PASS);
    let world = World::new();
    world.ci.set(State::Failure);
    let (report, _) = go(&pair, &world, Mode::Run);

    assert_eq!(stopped_at(&report), "ci", "{report:#?}");
    let release_commit = pair.head();
    assert_eq!(
        pair.origin(&["rev-parse", "main"]),
        release_commit,
        "pushed"
    );
    assert_eq!(
        pair.origin(&["tag", "--list", "v0.3.0"]),
        "",
        "a red CI never gets a tag"
    );
    assert!(pair.checkpoint().exists());

    // A second run does not start another release on top.
    let (again, _) = go(&pair, &world, Mode::Run);
    assert_eq!(stopped_at(&again), "plan");
    assert!(again.stopped().expect("stopped").summary.contains("resume"));

    // The fix is a new commit; resume pushes it, waits, tags it.
    pair.write("FIX.md", "fixed\n");
    pair.commit("fix: make CI green", NOW);
    world.ci.set(State::Success);
    let (report, _) = go(&pair, &world, Mode::Resume);
    assert!(report.released, "{report:#?}");
    let fixed = pair.head();
    assert_ne!(fixed, release_commit);
    assert_eq!(
        pair.origin(&["rev-parse", "v0.3.0^{commit}"]),
        fixed,
        "the tag names the green commit"
    );
    assert_eq!(status(&report, "commit"), StepStatus::Done);
    assert!(!pair.checkpoint().exists());
}

