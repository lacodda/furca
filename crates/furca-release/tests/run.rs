//! The run on repositories built by `git` in a temp directory, pushing to a
//! bare repository next to them. The forge, the registries and the record
//! are played by fakes; the gate is real shell commands that pass or fail.

use std::cell::{Cell, RefCell};
use std::path::{Path, PathBuf};
use std::process::Command;
use std::rc::Rc;
use std::time::{Duration, UNIX_EPOCH};

use furca_release::hosting::{Forge, Pace, Page, Run, State};
use furca_release::{
    CHECKPOINT, Provider, Reading, Record, Registries, Registry, Release, Report, Runner, Shipped,
    StepStatus,
};
use semver::Version;

/// The moment every run here is made at.
const NOW: u64 = 1_790_000_000;
const DAY: u64 = 86_400;

const CARGO: &str = r#"[package]
name = "demo"
description = "A demo crate."
version = "0.2.0"
edition = "2024"
readme = "README.md"
"#;

const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo"
version = "0.2.0"
"#;

const CLIFF: &str = r##"[changelog]
header = "# Changelog\n"
body = """
## [{{ version | trim_start_matches(pat="v") }}]
{% for group, commits in commits | group_by(attribute="group") %}
### {{ group }}
{% for commit in commits %}- {{ commit.message | upper_first }}
{% endfor %}{% endfor %}"""
trim = true

[git]
conventional_commits = true
filter_unconventional = true
commit_parsers = [
  { message = "^feat", group = "Features" },
  { message = "^fix", group = "Bug Fixes" },
  { message = "^chore", skip = true },
]
"##;

fn release_toml(gate: &str) -> String {
    format!(
        r#"[project]
name = "demo"
changelog = "CHANGELOG.md"
manifests = ["Cargo.toml"]

[gate]
commands = [{gate}]

[ci]
provider = "github"
workflow = "ci.yml"
publish = "publish.yml"

[[package]]
registry = "crates"
name = "demo"
manifest = "Cargo.toml"

[[post]]
kind = "install"
"#
    )
}

/// A released project at 0.2.0 with a feature since, and the bare
/// repository it pushes to.
struct Pair {
    dir: tempfile::TempDir,
}

impl Pair {
    fn new(gate: &str) -> Pair {
        let pair = Pair {
            dir: tempfile::tempdir().expect("temp dir"),
        };
        std::fs::create_dir_all(pair.work()).expect("work dir");
        std::fs::create_dir_all(pair.dir.path().join("no-hooks")).expect("hooks dir");
        git(
            pair.dir.path(),
            &[
                "init",
                "--quiet",
                "--bare",
                "--initial-branch=main",
                "origin.git",
            ],
            NOW,
        );
        let work = pair.work();
        git(&work, &["init", "--quiet", "--initial-branch=main"], NOW);
        let hooks = pair.dir.path().join("no-hooks");
        // The engine's own git reads the machine's configuration; the
        // repository's own values win over it.
        for (key, value) in [
            ("user.name", "Ada Author"),
            ("user.email", "ada@example.com"),
            ("commit.gpgsign", "false"),
            ("tag.gpgsign", "false"),
            ("core.autocrlf", "false"),
            ("core.hooksPath", hooks.to_str().expect("utf-8")),
        ] {
            git(&work, &["config", key, value], NOW);
        }
        let origin = pair.origin_path();
        git(
            &work,
            &["remote", "add", "origin", origin.to_str().expect("utf-8")],
            NOW,
        );

        pair.write("Cargo.toml", CARGO);
        pair.write("Cargo.lock", LOCK);
        pair.write("README.md", "# demo\n\nInstall v0.2.0 from the release.\n");
        pair.write("CHANGELOG.md", "# Changelog\n\n## [0.2.0]\n\n- First\n");
        pair.write("cliff.toml", CLIFF);
        pair.write(".github/workflows/ci.yml", "name: CI\n");
        pair.write(".github/workflows/publish.yml", "name: Publish\n");
        pair.write("release.toml", &release_toml(gate));
        pair.commit("chore: found the project", NOW - 30 * DAY);
        git(
            &work,
            &["tag", "-a", "v0.2.0", "-m", "v0.2.0"],
            NOW - 30 * DAY,
        );
        pair.commit("chore(deps): update the toolchain", NOW - DAY);
        pair.commit("feat: add a command", NOW - DAY);
        git(
            &work,
            &[
                "push",
                "--quiet",
                "--set-upstream",
                "origin",
                "main",
                "v0.2.0",
            ],
            NOW,
        );
        pair
    }

    fn work(&self) -> PathBuf {
        self.dir.path().join("work")
    }

    fn origin_path(&self) -> PathBuf {
        self.dir.path().join("origin.git")
    }

    fn write(&self, path: &str, text: &str) {
        let full = self.work().join(path);
        std::fs::create_dir_all(full.parent().expect("a parent")).expect("dirs");
        std::fs::write(full, text).expect("write");
    }

    fn read(&self, path: &str) -> String {
        std::fs::read_to_string(self.work().join(path)).expect("read")
    }

    fn commit(&self, message: &str, at: u64) {
        git(&self.work(), &["add", "--all"], at);
        git(
            &self.work(),
            &["commit", "--quiet", "--allow-empty", "-m", message],
            at,
        );
    }

    fn head(&self) -> String {
        git(&self.work(), &["rev-parse", "HEAD"], NOW)
    }

    fn origin(&self, args: &[&str]) -> String {
        git(&self.origin_path(), args, NOW)
    }

    fn checkpoint(&self) -> PathBuf {
        self.work().join(".git").join(CHECKPOINT)
    }
}

/// The test's own `git`, with the machine's configuration shut out and the
/// dates pinned.
fn git(dir: &Path, args: &[&str], at: u64) -> String {
    let empty = std::env::temp_dir().join("furca-release-tests.gitconfig");
    if !empty.exists() {
        std::fs::write(&empty, "").expect("empty config");
    }
    let date = format!("{at} +0000");
    let output = Command::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_CONFIG_GLOBAL", &empty)
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_AUTHOR_NAME", "Ada Author")
        .env("GIT_AUTHOR_EMAIL", "ada@example.com")
        .env("GIT_COMMITTER_NAME", "Ada Author")
        .env("GIT_COMMITTER_EMAIL", "ada@example.com")
        .env("GIT_AUTHOR_DATE", &date)
        .env("GIT_COMMITTER_DATE", &date)
        .output()
        .expect("git runs");
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout)
        .expect("utf-8")
        .trim()
        .to_owned()
}

/// The world outside the repository: how CI and the publish workflow end,
/// what the registry holds, what the record was told.
struct World {
    ci: Cell<State>,
    publish: Cell<State>,
    /// The workflow that puts out the release page, started by the tag too.
    release: Cell<State>,
    /// What the registry holds of `demo`; `None` before its first publish.
    held: RefCell<Option<Vec<Version>>>,
    /// The publish workflow puts the new version in the registry when it
    /// passes, as the real one does.
    publishes: Version,
    shipped: RefCell<Vec<Shipped>>,
    forge_asked: Cell<usize>,
}

impl World {
    fn new() -> Rc<World> {
        Rc::new(World {
            ci: Cell::new(State::Success),
            publish: Cell::new(State::Success),
            release: Cell::new(State::Success),
            held: RefCell::new(Some(vec![Version::new(0, 2, 0)])),
            publishes: Version::new(0, 3, 0),
            shipped: RefCell::new(Vec::new()),
            forge_asked: Cell::new(0),
        })
    }
}

struct FakeForge(Rc<World>);

impl Forge for FakeForge {
    fn runs(&self, _sha: &str) -> Result<Vec<Run>, String> {
        self.0.forge_asked.set(self.0.forge_asked.get() + 1);
        let run = |workflow: &str, reference: &str, state: State| Run {
            id: 1,
            workflow: workflow.to_owned(),
            name: workflow.to_owned(),
            event: "push".to_owned(),
            reference: Some(reference.to_owned()),
            state,
            url: format!("https://ci.example/{workflow}"),
        };
        if self.0.publish.get() == State::Success
            && let Some(held) = self.0.held.borrow_mut().as_mut()
            && !held.contains(&self.0.publishes)
        {
            held.push(self.0.publishes.clone());
        }
        Ok(vec![
            run("ci.yml", "main", self.0.ci.get()),
            run("publish.yml", "v0.3.0", self.0.publish.get()),
            run("release.yml", "v0.3.0", self.0.release.get()),
        ])
    }

    fn page(&self, tag: &str) -> Result<Option<Page>, String> {
        Ok(Some(Page {
            draft: false,
            assets: vec![format!("demo-{tag}-x86_64.zip")],
            url: format!("https://forge.example/releases/{tag}"),
        }))
    }

    fn actions_url(&self) -> String {
        "https://forge.example/actions".to_owned()
    }

    fn pace(&self) -> Pace {
        Pace {
            every: Duration::from_secs(1),
            appear: Duration::from_secs(3),
            limit: Duration::from_secs(10),
        }
    }
}

struct FakeRegistries(Rc<World>);

impl Registries for FakeRegistries {
    fn versions(&self, registry: Registry, name: &str) -> Result<Option<Vec<Version>>, String> {
        assert_eq!((registry, name), (Registry::Crates, "demo"));
        Ok(self.0.held.borrow().clone())
    }
}

struct FakeRecord(Rc<World>);

impl Record for FakeRecord {
    fn read(&self, _name: &str, _root: &Path) -> Reading {
        Reading::Absent("the test keeps no record".to_owned())
    }

    fn shipped(&self, _name: &str, _root: &Path, shipped: &Shipped) -> Result<(), String> {
        self.0.shipped.borrow_mut().push(shipped.clone());
        Ok(())
    }
}

enum Mode {
    Run,
    Resume,
}

/// Runs or resumes the release in `pair` against `world`, and returns the
/// report and every line the run said.
fn go(pair: &Pair, world: &Rc<World>, mode: Mode) -> (Report, Vec<String>) {
    let release = Release::open(pair.work()).expect("release.toml reads");
    let registries = FakeRegistries(world.clone());
    let record = FakeRecord(world.clone());
    let forge_world = world.clone();
    let forge = move |_url: &str, provider: Provider| -> Option<Box<dyn Forge>> {
        assert_eq!(provider, Provider::Github);
        Some(Box::new(FakeForge(forge_world.clone())))
    };
    let mut said = Vec::new();
    let mut say = |step: &str, line: &str| said.push(format!("{step}: {line}"));
    let mut runner = Runner {
        registries: &registries,
        record: Some(&record),
        forge: &forge,
        now: &|| UNIX_EPOCH + Duration::from_secs(NOW),
        sleep: &|_| {},
        gate_to_stderr: true,
        say: &mut say,
    };
    let report = match mode {
        Mode::Run => release.run(&mut runner),
        Mode::Resume => release.resume(&mut runner),
    }
    .expect("the run answers");
    (report, said)
}

fn status(report: &Report, step: &str) -> StepStatus {
    report
        .steps
        .iter()
        .find(|s| s.name == step)
        .unwrap_or_else(|| panic!("no step {step}"))
        .status
}

fn stopped_at(report: &Report) -> &str {
    report.stopped().map_or("nowhere", |s| s.name)
}

const PASS: &str = r#""exit 0""#;

#[test]
fn a_run_goes_from_the_plan_to_the_record() {
    let pair = Pair::new(PASS);
    let world = World::new();
    let (report, said) = go(&pair, &world, Mode::Run);

    assert!(report.released, "{report:#?}\n{said:#?}");
    assert_eq!(report.tag.as_deref(), Some("v0.3.0"));
    for step in [
        "plan",
        "bump",
        "changelog",
        "gate",
        "commit",
        "push",
        "ci",
        "tag",
        "publish",
        "record",
    ] {
        assert_eq!(
            status(&report, step),
            StepStatus::Done,
            "{step}: {report:#?}"
        );
    }

    // The files say the new number, the lockfile's entry with them.
    assert!(pair.read("Cargo.toml").contains("version = \"0.3.0\""));
    assert!(
        pair.read("Cargo.lock")
            .contains("name = \"demo\"\nversion = \"0.3.0\"")
    );
    assert!(pair.read("README.md").contains("Install v0.3.0 from"));
    let changelog = pair.read("CHANGELOG.md");
    assert!(
        changelog.starts_with(
            "# Changelog\n\n## [0.3.0]\n\n### Features\n- Add a command\n\n## [0.2.0]\n\n- First\n"
        ),
        "{changelog}"
    );

    // One commit, pushed, tagged, and nothing left behind.
    let head = pair.head();
    assert_eq!(report.commit.as_deref(), Some(head.as_str()));
    assert_eq!(
        git(&pair.work(), &["log", "-1", "--format=%s"], NOW),
        "chore(release): v0.3.0"
    );
    assert_eq!(pair.origin(&["rev-parse", "main"]), head);
    assert_eq!(pair.origin(&["rev-parse", "v0.3.0^{commit}"]), head);
    assert_eq!(
        pair.origin(&["cat-file", "-t", "v0.3.0"]),
        "tag",
        "annotated"
    );
    assert_eq!(git(&pair.work(), &["status", "--porcelain"], NOW), "");
    assert!(!pair.checkpoint().exists());

    assert_eq!(report.registries, ["crates.io"]);
    let shipped = world.shipped.borrow();
    assert_eq!(shipped.len(), 1);
    assert_eq!(shipped[0].tag, "v0.3.0");
    assert!(shipped[0].release);
    assert_eq!(shipped[0].registries, ["crates.io"]);
    assert_eq!(
        report.after,
        ["install the released build with the repository's installer"]
    );
    assert!(
        report
            .git
            .iter()
            .any(|run| run.command() == "git push --quiet origin refs/tags/v0.3.0"),
        "{:#?}",
        report.git
    );
}

#[test]
fn a_red_gate_takes_the_edits_back() {
    let pair = Pair::new(r#""exit 0", "exit 3""#);
    let before = ["Cargo.toml", "Cargo.lock", "README.md", "CHANGELOG.md"].map(|p| pair.read(p));
    let head = pair.head();
    let world = World::new();
    let (report, _) = go(&pair, &world, Mode::Run);

    assert_eq!(stopped_at(&report), "gate", "{report:#?}");
    let gate = report.stopped().expect("stopped");
    assert_eq!(gate.summary, "`exit 3` exited 3");
    assert_eq!(status(&report, "commit"), StepStatus::Ahead);
    let after = ["Cargo.toml", "Cargo.lock", "README.md", "CHANGELOG.md"].map(|p| pair.read(p));
    assert_eq!(after, before, "every edit is taken back");
    assert_eq!(pair.head(), head, "nothing is committed");
    assert!(
        !pair.checkpoint().exists(),
        "a stop before the commit leaves no checkpoint"
    );
    assert_eq!(world.forge_asked.get(), 0, "nothing reached the forge");
}

