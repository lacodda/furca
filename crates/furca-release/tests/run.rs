#[test]
fn a_red_publish_is_carried_on_once_the_registry_holds_the_version() {
    let pair = Pair::new(PASS);
    let world = World::new();
    world.publish.set(State::Failure);
    let (report, _) = go(&pair, &world, Mode::Run);
    assert_eq!(stopped_at(&report), "publish", "{report:#?}");
    assert_eq!(
        pair.origin(&["rev-parse", "v0.3.0^{commit}"]),
        pair.head(),
        "the tag is out"
    );

    // Published by a re-run started from another commit: the registry is
    // what counts, and the red publish workflow no longer does. The release
    // page's workflow still has to end green.
    world
        .held
        .borrow_mut()
        .as_mut()
        .expect("held")
        .push(Version::new(0, 3, 0));
    world.release.set(State::Failure);
    let (report, _) = go(&pair, &world, Mode::Resume);
    assert_eq!(stopped_at(&report), "publish", "{report:#?}");
    let publish = report.stopped().expect("stopped");
    assert!(
        publish
            .details
            .iter()
            .any(|d| d.starts_with("release.yml failed"))
            && !publish.details.iter().any(|d| d.starts_with("publish.yml")),
        "{publish:#?}"
    );
    assert!(world.shipped.borrow().is_empty(), "nothing recorded yet");

    world.release.set(State::Success);
    let (report, _) = go(&pair, &world, Mode::Resume);
    assert!(report.released, "{report:#?}");
    assert_eq!(status(&report, "tag"), StepStatus::Skipped);
}

#[test]
fn a_dirty_tree_or_a_branch_behind_its_remote_stops_before_anything() {
    let pair = Pair::new(PASS);
    let world = World::new();
    pair.write("README.md", "# demo\n\nchanged\n");
    let (report, _) = go(&pair, &world, Mode::Run);
    assert_eq!(stopped_at(&report), "plan");
    assert_eq!(report.stopped().expect("stopped").details, ["README.md"]);
    git(&pair.work(), &["checkout", "--", "README.md"], NOW);

    // The remote moves on without this clone.
    let other = pair.dir.path().join("other");
    git(
        pair.dir.path(),
        &[
            "clone",
            "--quiet",
            pair.origin_path().to_str().expect("utf-8"),
            "other",
        ],
        NOW,
    );
    std::fs::write(other.join("NEW.md"), "new\n").expect("write");
    git(&other, &["add", "--all"], NOW);
    git(
        &other,
        &[
            "-c",
            "user.name=B",
            "-c",
            "user.email=b@example.com",
            "commit",
            "--quiet",
            "-m",
            "docs: elsewhere",
        ],
        NOW,
    );
    git(&other, &["push", "--quiet"], NOW);
    let (report, _) = go(&pair, &world, Mode::Run);
    assert_eq!(stopped_at(&report), "plan", "{report:#?}");
    assert!(
        report
            .stopped()
            .expect("stopped")
            .summary
            .contains("pull them first")
    );
    assert!(pair.read("Cargo.toml").contains("0.2.0"));
}
