#[test]
fn an_interrupted_run_is_taken_back_by_the_next() {
    let pair = Pair::new(PASS);
    let world = World::new();
    let before = pair.read("Cargo.toml");
    // The run is killed while the gate runs: the edits are on disk and the
    // checkpoint says so.
    let killed = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        let release = Release::open(pair.work()).expect("reads");
        let registries = FakeRegistries(world.clone());
        let forge = |_: &str, _: Provider| -> Option<Box<dyn Forge>> { None };
        let mut say = |step: &str, _: &str| {
            if step == "gate" {
                panic!("killed");
            }
        };
        let mut runner = Runner {
            registries: &registries,
            record: None,
            forge: &forge,
            now: &|| UNIX_EPOCH + Duration::from_secs(NOW),
            sleep: &|_| {},
            gate_to_stderr: true,
            say: &mut say,
        };
        let _ = release.run(&mut runner);
    }));
    assert!(killed.is_err());
    assert!(
        pair.read("Cargo.toml").contains("0.3.0"),
        "the bump was on disk"
    );
    assert!(pair.checkpoint().exists());

    let (report, said) = go(&pair, &world, Mode::Run);
    assert!(
        said.iter()
            .any(|l| l.contains("took back the edits of an interrupted run of v0.3.0")),
        "{said:#?}"
    );
    assert!(report.released, "{report:#?}");
    assert_ne!(pair.read("Cargo.toml"), before);
    assert_eq!(
        pair.read("CHANGELOG.md").matches("## [0.3.0]").count(),
        1,
        "one section, not two"
    );
}

#[test]
